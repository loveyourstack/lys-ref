import type { SchemaTable } from '@/types/core'

function qt(t: SchemaTable) {
  return `${t.schema || 'public'}.${t.name}`
}

function schemaNames(tables: SchemaTable[]) {
  return [...new Set(tables.map(t => t.schema || 'public'))].filter(s => s !== 'public')
}

interface ResolvedFk {
  column: string
  refTable: SchemaTable
  refColumn: string
}

function resolveFks(t: SchemaTable, tables: SchemaTable[]): ResolvedFk[] {
  const fks: ResolvedFk[] = []
  for (const c of t.columns) {
    if (!c.ref) continue
    const refTable = tables.find(o => o.id === c.ref!.table_id)
    const refCol = refTable?.columns.find(o => o.id === c.ref!.column_id)
    if (!refTable || !refCol) continue
    fks.push({ column: c.name, refTable, refColumn: refCol.name })
  }
  return fks
}

// orders tables so referenced tables come first (self-references ignored); on a cycle, the first remaining table is taken
function creationOrder(tables: SchemaTable[], fks: Map<string, ResolvedFk[]>): SchemaTable[] {
  const ordered: SchemaTable[] = []
  const created = new Set<string>()
  let remaining = [...tables]
  while (remaining.length > 0) {
    const next =
      remaining.find(t => fks.get(t.id)!.every(f => f.refTable.id === t.id || created.has(f.refTable.id))) ?? remaining[0]!
    ordered.push(next)
    created.add(next.id)
    remaining = remaining.filter(t => t !== next)
  }
  return ordered
}

function fkClause(f: ResolvedFk) {
  return `FOREIGN KEY (${f.column}) REFERENCES ${qt(f.refTable)}(${f.refColumn})`
}

// generates PostgreSQL DDL: tables in FK dependency order with FKs inline;
// FKs that cannot be inline (circular references) are added with ALTER TABLE at the end
export function generateSchemaSql(tables: SchemaTable[]): string {
  const schemas = schemaNames(tables).map(s => `CREATE SCHEMA IF NOT EXISTS ${s};`)

  const fks = new Map(tables.map(t => [t.id, resolveFks(t, tables)]))
  const created = new Set<string>()
  const creates: string[] = []
  const deferred: string[] = []

  for (const t of creationOrder(tables, fks)) {
    const tableFks = fks.get(t.id)!
    const lines = t.columns.map(c => {
      const fk = tableFks.find(f => f.column === c.name)
      const parts = [`${c.name} ${c.pk ? 'bigint' : c.type}`]
      if (c.pk) {
        parts.push('GENERATED BY DEFAULT AS IDENTITY', 'PRIMARY KEY')
      } else if (c.not_null) {
        parts.push('NOT NULL')
      }
      if (fk && (fk.refTable.id === t.id || created.has(fk.refTable.id))) {
        parts.push(`REFERENCES ${qt(fk.refTable)}(${fk.refColumn})`)
      } else if (fk) {
        deferred.push(`ALTER TABLE ${qt(t)} ADD ${fkClause(fk)};`)
      }
      return `  ${parts.join(' ')}`
    })
    creates.push(`CREATE TABLE ${qt(t)} (\n${lines.join(',\n')}\n);`)
    created.add(t.id)
  }

  return [...schemas, ...creates, ...deferred].join('\n\n') + '\n'
}
